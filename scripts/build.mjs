// Copies the shared contribution library into src/, builds the radar view into one HTML file, then bundles the server,
// its packages, the data and the view into dist/index.mjs, a single file that runs with Node 20 or later and nothing else.
import { build } from 'esbuild';
import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const at = (...p) => path.join(ROOT, ...p);
const nodePaths = [];
await fs.mkdir(at('dist'), { recursive: true });

// 0. the contribution library the server shares with the review desk: one source, community/lib/contribution.mjs, copied into
// src/contribution.js so that the published package carries the code it was built from;
// and, with it, the review policy and the review desk's reading of an issue's events (community/lib/policy.mjs and
// community/github/.github/desk/state.mjs), so that the server reads a contribution's status exactly as the desk does
const COPIES = [
  ['community/lib/contribution.mjs', 'src/contribution.js', (t) => t],
  ['community/lib/policy.mjs', 'src/policy.js', (t) => t],
  ['community/github/.github/desk/state.mjs', 'src/desk-state.js', (t) => t.replace("from './lib/policy.mjs'", "from './policy.js'")],
];
for (const [from, to, fix] of COPIES) {
  const header = `// GENERATED by mcp/scripts/build.mjs from ${from}, shared with the review desk and the CHAP recorder.\n`
    + `// Do not edit this copy: change ${from} and rebuild.\n\n`;
  try {
    await fs.writeFile(at(to), header + fix(await fs.readFile(path.resolve(ROOT, '..', from), 'utf8')));
  } catch (err) {
    if (err.code !== 'ENOENT' || !(await fs.stat(at(to)).catch(() => null))) throw err;
    console.log(`mcp: ${from} not found; bundling the copy already in ${to}`);
  }
}
// the review desk, which the end-to-end tests run against, copied as it is into vendor/review-desk/ so that the server's
// own repository (BrightbeamAI/intelligence-radar-mcp) can run every test; not part of the npm package
const DESK = path.resolve(ROOT, '..', 'community', 'github', '.github', 'desk');
if (await fs.stat(path.join(DESK, 'desk.mjs')).catch(() => null)) {
  for (const f of ['api.mjs', 'desk.mjs', 'roster.mjs', 'state.mjs', 'lib/contribution.mjs', 'lib/policy.mjs', 'lib/config.json', 'lib/forms.json', 'test/fake-github.mjs']) {
    await fs.mkdir(path.dirname(at('vendor', 'review-desk', f)), { recursive: true });
    await fs.copyFile(path.join(DESK, f), at('vendor', 'review-desk', f));
  }
}

// 1. the view: its script, styles, data, both radars and the font in one file
const script = await build({
  entryPoints: [at('src/view/radar-view.js')], bundle: true, format: 'iife', platform: 'browser', target: 'es2020',
  minify: true, legalComments: 'none', write: false, nodePaths, absWorkingDir: ROOT, logLevel: 'warning',
});
const radar = JSON.parse(await fs.readFile(at('data/radar.json'), 'utf8'));
const view = {
  version: radar.version,
  edition: radar.edition,
  labels: { intelligence: radar.labels.intelligence.map(({ name, short }) => ({ name, short })),
    enterprise: radar.labels.enterprise.map(({ name, short }) => ({ name, short })) },
  dimensions: radar.dimensions.map(({ number, name, short, question, colour, url }) => ({ number, name, short, question, colour, url })),
  entries: radar.entries.map(({ id, number, title, dimension, intelligence, enterprise, summary, where, test, failure, examples, owner, url }) =>
    ({ id, number, title, dimension, intelligence, enterprise, summary, where, test, failure, examples, owner, url })),
  // the sector lens: what binds, where to start, the entries placed differently and what to hold back
  sectors: (radar.sectors || []).map(({ slug, name, scope, headline, rules, start, moves, hold, relevant, url, card }) =>
    ({ slug, name, scope, headline, rules, start, moves, hold, relevant, url, card })),
};
const font = (await fs.readFile(at('data/font.woff2'))).toString('base64');
const fontFace = `@font-face{font-family:'Zalando Sans';src:url(data:font/woff2;base64,${font}) format('woff2');font-weight:100 900;font-style:normal;font-display:swap}`;
const css = await fs.readFile(at('src/view/radar-view.css'), 'utf8');
const safe = (s) => s.replace(/<\/(script|template)/gi, '<\\/$1');
const svg = async (theme) => (await fs.readFile(at(`data/radar-${theme}.svg`), 'utf8'));
let html = await fs.readFile(at('src/view/radar-view.html'), 'utf8');
const put = (marker, value) => { html = html.split(marker).join(value); };
put('/*FONT*/', fontFace);
put('/*CSS*/', css);
put('/*DATA*/', safe(JSON.stringify(view)));
put('<!--SVG_LIGHT-->', await svg('light'));
put('<!--SVG_DARK-->', await svg('dark'));
put('/*JS*/', safe(script.outputFiles[0].text));
await fs.writeFile(at('dist/radar-view.html'), html);

// 2. the server, with everything it needs inside
await build({
  entryPoints: [at('src/index.js')], bundle: true, platform: 'node', format: 'esm', target: 'node20',
  outfile: at('dist/index.mjs'), loader: { '.md': 'text', '.html': 'text' }, legalComments: 'eof',
  banner: { js: "import { createRequire as __radarRequire } from 'node:module'; const require = __radarRequire(import.meta.url);" },
  nodePaths, absWorkingDir: ROOT, logLevel: 'warning', minifyWhitespace: true, minifySyntax: true,
});
const out = await fs.stat(at('dist/index.mjs'));
console.log(`mcp: view ${Math.round(html.length / 1024)} KB; server dist/index.mjs ${Math.round(out.size / 1024)} KB`);
